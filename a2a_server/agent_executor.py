
# agent_executor.py

from a2a.server.agent_execution import (
    AgentExecutor,
    RequestContext
)

from a2a.server.events import EventQueue

from a2a.server.tasks import TaskUpdater

from a2a.types.a2a_pb2 import TaskState

from a2a.helpers import (
    get_message_text,
    new_task_from_user_message,
    new_text_message,
    new_text_part
)


# ==========================================
# 1. AGENT BUSINESS LOGIC
# ==========================================

class HelloWorldAgent:

    async def invoke(self, user_request: str) -> str:

        question = user_request.strip()

        if not question:
            question = "Hello"

        answer = (
            "Hello from PragyanAI A2A Server!\n\n"
            f"Your request: {question}\n\n"
            "This response was generated by a remote "
            "A2A agent using the official Python SDK."
        )

        return answer


# ==========================================
# 2. A2A AGENT EXECUTOR
# ==========================================

class HelloWorldAgentExecutor(AgentExecutor):

    def __init__(self):

        self.agent = HelloWorldAgent()

    # --------------------------------------
    # Execute incoming A2A task
    # --------------------------------------

    async def execute(
        self,
        context: RequestContext,
        event_queue: EventQueue
    ) -> None:

        # Step 1: Get existing task
        task = context.current_task

        # Step 2: Create task if new
        if task is None:

            task = new_task_from_user_message(
                context.message
            )

            await event_queue.enqueue_event(task)

        # Step 3: Initialize TaskUpdater
        updater = TaskUpdater(
            event_queue=event_queue,
            task_id=task.id,
            context_id=task.context_id
        )

        try:

            # Step 4: Mark task as working
            await updater.update_status(
                state=TaskState.TASK_STATE_WORKING,
                message=new_text_message(
                    "PragyanAI Agent is processing your request..."
                )
            )

            # Step 5: Extract user input
            user_request = get_message_text(
                context.message
            )

            # Step 6: Execute agent logic
            answer = await self.agent.invoke(
                user_request
            )

            # Step 7: Create result artifact
            await updater.add_artifact(
                parts=[
                    new_text_part(
                        text=answer
                    )
                ]
            )

            # Step 8: Mark task completed
            await updater.update_status(
                state=TaskState.TASK_STATE_COMPLETED,
                message=new_text_message(
                    "Agent completed successfully."
                )
            )

        except Exception as error:

            # Mark task failed
            await updater.update_status(
                state=TaskState.TASK_STATE_FAILED,
                message=new_text_message(
                    f"Agent execution failed: {str(error)}"
                )
            )

            raise

    # --------------------------------------
    # Cancel incoming task
    # --------------------------------------

    async def cancel(
        self,
        context: RequestContext,
        event_queue: EventQueue
    ) -> None:

        raise NotImplementedError(
            "Task cancellation is not implemented."
        )
